""" What wl_cloud actually contains: the workload census, DERIVED (`WORKLOAD.md`).

The question this answers is the one asked of every benchmark -- how many
devices of which type, what topology, how many ACL and forwarding rules, which
header fields -- and the reason it is a module rather than a section of prose is
CLOUD_BENCH_PLAN.md §1.8. A census typed into a document by hand is
`oracle.json`'s original defect in a cheaper costume: nothing can notice when it
stops being true, and "86 devices" reads exactly as authoritative whether it was
measured this morning or guessed two years ago.

So `WORKLOAD.md` is GENERATED by this module and pinned by
`test/test_cloud_census.py`, which re-derives it from the vendored raw data and
compares byte for byte. Editing the document by hand is a test failure; changing
the reading of the dataset without regenerating it is also a test failure.

**Two numbers in CLOUD_BENCH_PLAN.md do not survive this derivation**, and both
are recorded in the document itself rather than silently corrected:

  1. §1.3's "~1,722 table rules" is 1,741. It was computed as 2,941 - 1,219,
     subtracting the internet gateway's 19 rules along with the 1,200 host
     injectors -- while also counting the gateway as one of the 86 tables. The
     gateway's rules ARE table rules. `routes.json` has carried 1,741 entries
     all along, so the model was never wrong; only the figure describing it was.

  2. §1.1's "~1,555" for `packet.ipv4.source` is 1,558. The tilde is the tell:
     that table mixes two different measurements. Per-BIT density genuinely
     varies across an IP field, because a /22 constrains 22 of its 32 bits and a
     /30 constrains 30 -- source runs 1,558 down to 0 and destination 1,682 down
     to 14. This module counts RULES WHOSE FIELD IS NOT FULLY WILDCARDED, one
     well-defined number per field, which is why no row here needs a tilde.

`85` versus `86` is NOT such a disagreement, and the distinction is worth
keeping. §1.2 classifies by "appears as both a rule in-port and an out-port",
which yields 85 and then adds the gateway back by hand. `cloud_tf.classify_nodes`
classifies by "has rules of its own", which yields 86 directly. The gateway is
the whole difference: every one of its 19 rules either DROPS or NATs, so it
never appears as anybody's out-port, and the structural test would file a
drop-only device as a traffic source. Both readings agree on the model; one of
them needs a footnote to get there.
"""

