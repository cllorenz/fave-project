class CensusError(Exception):
    """ A node or rule this module will not silently file somewhere. """


#: Device classes, keyed by what `cloud_tf.node_name` calls them. Ordered
#: north to south so the rendered tables read as the topology does.
_DEVICE_CLASSES: Sequence[Tuple[str, 're.Pattern']] = (
    ('internet_gw', re.compile(r'internet_gw$')),
    ('core', re.compile(r'dc\d+_core$')),
    ('leaf_in', re.compile(r'dc\d+_leaf\d+_in$')),
    ('leaf_out', re.compile(r'dc\d+_leaf\d+_out$')),
)

#: Non-device node classes: the generators and the probes.
_ENDPOINT_CLASSES: Sequence[Tuple[str, 're.Pattern']] = (
    ('host_tx', re.compile(r'dc\d+_leaf\d+_host\d+_tx$')),
    ('host_rx', re.compile(r'dc\d+_leaf\d+_host\d+_rx$')),
    ('internet_rx', re.compile(r'internet_rx$')),
)

#: What each device class is, in one line, for the rendered table.
_CLASS_PROSE: Dict[str, str] = {
    'internet_gw': 'the one gateway: anti-spoof filter and inbound destination-NAT',
    'core': 'datacenter cores: inter-leaf and inter-datacenter routing, outbound source-NAT',
    'leaf_in': 'leaf-router ingress: the ACL, and the decision to go up or across',
    'leaf_out': 'leaf-router egress: host distribution, nothing else',
    'host_tx': 'host transmit nodes -> FaVe generators',
    'host_rx': 'host receive nodes -> FaVe probes',
    'internet_rx': 'the internet egress sink -> one more probe',
}

#: The four functions a device rule can have. Structural definitions, in the
#: order they are tested -- a rule is classified by what it DOES, never by which
#: device it sits on, so the taxonomy cannot beg the question it is asked.
_RULE_FUNCTIONS = ('deny', 'nat', 'acl-permit', 'forward')

_RULE_FUNCTION_PROSE: Dict[str, str] = {
    'deny': 'no out-port: the packet is discarded',
    'nat': 'a `rw` rule: it rewrites the address it forwards on',
    'acl-permit': 'constrains a transport port, so it admits a SERVICE rather than a destination',
    'forward': 'everything else: a routing decision on the destination alone, or an unconditioned uplink',
}

_TRANSPORT_FIELDS = ('packet.upper.sport', 'packet.upper.dport')


def device_class(name: str) -> str:
    """ Which device class a node name belongs to. Refuses the unclassified.

    A default bucket here would let a node the reading does not understand be
    counted as though it were understood, which is the failure §1.8 is about.
    """
    for label, pattern in _DEVICE_CLASSES:
        if pattern.match(name):
            return label
    raise CensusError("no device class for node %r" % name)


def endpoint_class(name: str) -> str:
    """ Which endpoint class a non-device node belongs to. Refuses likewise. """
    for label, pattern in _ENDPOINT_CLASSES:
        if pattern.match(name):
            return label
    raise CensusError("no endpoint class for node %r" % name)


def rule_function(rule: Rule) -> str:
    """ What a rule does, from its own shape.

    The ACL test is "constrains a transport port". That is what distinguishes
    an access rule from a routing rule in this dataset -- the generator emits
    permissions as `dst in <service prefix>, proto = tcp, dport = 331+i`, and
    emits routing as a destination prefix and nothing else. Testing the device
    instead ("rules at a leaf ingress are ACLs") would assume the answer.
    """
    if rule.is_drop:
        return 'deny'
    if rule.action == 'rw':
        return 'nat'
    if any(read_match_field(rule.match, f) is not None for f in _TRANSPORT_FIELDS):
        return 'acl-permit'
    return 'forward'


def _digest(path: str) -> str:
    with open(path, 'rb') as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def _oracle_inventory(path: str) -> Tuple[int, int]:
    """ (roles, services) the hand-written oracle phase runs with.

    `Internet` is added because FPL declares it BUILT IN -- `reach.txt` names it
    on three of its five rules and the inventory therefore never defines it, so
    counting `describe role` alone is one short of the 8 roles the run actually
    carries (`roles.json`, and `sources.json`'s 8 generators). The matrix phase
    needs no such correction: `cloud_policy.role_endpoints` already seeds the
    role map with `Internet` for exactly this reason.
    """
    text = open(path).read()
    return (
        len(re.findall(r'^describe\s+role\s', text, re.M)) + 1,
        len(re.findall(r'^describe\s+service\s', text, re.M)),
    )


def census(rules: List[Rule], model: NodeModel, readme: CloudReadme) -> Dict:
    """ Every number `WORKLOAD.md` states, derived from the raw data. """
    devices = collections.Counter(device_class(node_name(n)) for n in model.devices)
    endpoints = collections.Counter(
        endpoint_class(node_name(n)) for n in list(model.sources) + list(model.sinks))

    # rules per (device class, function)
    grid: Dict[Tuple[str, str], int] = collections.Counter()
    for node in model.devices:
        label = device_class(node_name(node))
        for rule in model.rules_at(node):
            grid[(label, rule_function(rule))] += 1

    # the ACL permits split by whether they constrain a source: the ones that
    # do are the matrix's private half, the ones that do not are public.
    sourced = collections.Counter()
    for node in model.devices:
        for rule in model.rules_at(node):
            if rule_function(rule) != 'acl-permit':
                continue
            has = read_match_field(rule.match, 'packet.ipv4.source') is not None
            sourced['sourced' if has else 'source-less'] += 1

    # the topology: device-to-device edges only. A host or internet edge is a
    # generator or a probe attachment, not a link, which is why `topology.json`
    # carries fewer links than the rules carry distinct node pairs.
    device_nodes = set(model.devices)
    links: Dict[Tuple[str, str], set] = collections.defaultdict(set)
    for rule in rules:
        for src in rule.in_ports:
            for dst in rule.out_ports:
                if src in device_nodes and dst in device_nodes:
                    links[(device_class(node_name(src)),
                           device_class(node_name(dst)))].add((src, dst))

    fields = {
        field: sum(
            1 for rule in rules if read_match_field(rule.match, field) is not None)
        for field in CLOUD_MAPPING if field != 'length'
    }

    matrix_endpoints = role_endpoints(readme)
    oracle_roles, oracle_services = _oracle_inventory(
        os.path.join(HERE, 'roles_and_services.txt'))

    return {
        'sha256': {name: _digest(os.path.join(RAW, name))
                   for name in ('network.tf', 'README.txt')},
        'rules_total': len(rules),
        'actions': collections.Counter(r.action for r in rules),
        'devices': devices,
        'endpoints': endpoints,
        'nodes_total': len(model.devices) + len(model.sources) + len(model.sinks),
        'grid': grid,
        'acl_sourced': sourced,
        'links': {pair: len(edges) for pair, edges in links.items()},
        'source_rules': sum(len(model.rules_at(n)) for n in model.sources),
        'device_rules': sum(len(model.rules_at(n)) for n in model.devices),
        'drop_nodes': len({p for r in rules if r.is_drop for p in r.in_ports}),
        'fields': fields,
        'protocols': sorted(
            {read_match_field(r.match, 'packet.ipv6.proto') for r in rules} - {None}),
        'ports': sorted(
            {read_match_field(r.match, f) for r in rules for f in _TRANSPORT_FIELDS}
            - {None}),
        'services': len(readme.services),
        'roles': len(readme.roles),
        'internet_index': readme.internet_index,
        'port_base': readme.service_port_base,
        'authorised_pairs': len(readme.authorised_pairs()),
        'matrix_symmetric': all(
            readme.permits(i, j) == readme.permits(j, i)
            for i in readme.roles for j in readme.roles),
        'matrix_diagonal': sum(1 for i in readme.roles if readme.permits(i, i)),
        'matrix_roles': len(matrix_endpoints),
        'matrix_endpoints': sum(len(v) for v in matrix_endpoints.values()),
        'oracle_roles': oracle_roles,
        'oracle_services': oracle_services,
        'mapping': dict(CLOUD_MAPPING),
        'fave_mapping': dict(FAVE_MAPPING),
    }


def _n(value: int) -> str:
    """ A count, in the plan's own thousands-separated spelling. """
    return '{:,}'.format(value)


def _table(header: Sequence[str], rows: Sequence[Sequence[str]],
           align: str = '') -> List[str]:
    align = align or 'l' * len(header)
    sep = {'l': '---', 'r': '---:', 'c': ':---:'}
    out = ['| ' + ' | '.join(header) + ' |',
           '|' + '|'.join(sep[a] for a in align) + '|']
    out.extend('| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows)
    return out


