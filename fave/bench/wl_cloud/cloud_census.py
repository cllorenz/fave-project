def build() -> str:
    """ Read the raw data and render the document. """
    with open(os.path.join(RAW, 'network.tf')) as handle:
        rules = parse_tf(handle)
    readme = read_readme(os.path.join(RAW, 'README.txt'))
    return render(census(rules, classify_nodes(rules), readme))


def main() -> None:
    document = build()
    with open(DOCUMENT, 'w') as handle:
        handle.write(document)
    print("wrote %s (%d bytes)" % (DOCUMENT, len(document)))


if __name__ == '__main__':
    main()
