#!/usr/bin/env python3

""" wl_tum's FPL inventory and policy, written from service_matrix.json
(owner, 2026-10-14): roles_and_services.txt and reach.txt.

FABRICATED: the dataset ships a ruleset and no policy. The roles, services
and rules here are read off the ruleset by service_matrix.py, which does not
use FaVe's engines -- the policy states what an independent reading of the
ruleset says, so checking the engines against it cross-checks them:

  * one service per TCP and UDP destination-port class (ports every rule
    treats alike) and one per portless protocol (icmp, esp, gre);
  * one role per host a rule names as a single destination, one per inside
    VLAN for the rest of its addresses, and the builtin Internet -- an
    anonymous outside prefix (service_matrix.INTERNET);
  * a role OFFERS the services its own rules name, every service the Internet
    reaches on it, and one port nobody administers per protocol
    (service_matrix.other_service): offered and unreachable is checked as
    must-not-reach;
  * `Internet <->> R.S` for every service S the Internet reaches on R, and
    `R <->> Internet` for every role that can open any connection out.

Traffic between inside roles is out of scope: the checks are restricted to
pairs with the Internet (reach_csv_to_checks.py --only-with Internet).
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MATRIX = os.path.join(HERE, 'service_matrix.json')
ROLES = os.path.join(HERE, 'roles_and_services.txt')
REACH = os.path.join(HERE, 'reach.txt')

HEADER = """# wl_tum's FPL %s, GENERATED by fplgen.py from service_matrix.json -- do not
# edit; regenerate. FABRICATED (owner, 2026-10-14): read off the ruleset by
# service_matrix.py, independently of FaVe's engines. See fplgen.py and
# WORKLOAD.md for what each role, service and rule stands for.

"""


def role_name(endpoint):
    """ An endpoint name as an FPL identifier: `B.S` takes the dot. """
    return endpoint.replace('.', '_')


def main():
    with open(MATRIX) as raw:
        m = json.load(raw)
    out = [HEADER % 'inventory']
    for name, (proto, ports) in sorted(m['services'].items()):
        out.append("describe service %s\n    protocol = '%s'\n%send\n\n" % (
            name, proto, '    port = %d\n' % ports[0] if ports else ''))
    for name, ep in sorted(m['endpoints'].items()):
        kind = 'host' if name.startswith('h') else 'VLAN %d without its named hosts' % ep['vlan']
        out.append("describe role %s\n    description = '%s %s on VLAN %d'\n"
                   "    hosts = [ '%s' ]\n    vlan = %d\n%s%send\n\n" % (
                       role_name(name), kind, ep['address'], ep['vlan'], name, ep['vlan'],
                       "    ipv4 = '%s'\n" % (ep['address'] if '/' in ep['address'] else ep['address'] + '/32'),
                       ''.join('    offers %s\n' % s for s in ep['offers'])))
    with open(ROLES, 'w') as fh:
        fh.write(''.join(out))
    rules = []
    for name, ep in sorted(m['endpoints'].items()):
        rules.extend('    Internet <->> %s.%s\n' % (role_name(name), s) for s in sorted(ep['inbound']))
        if ep['outbound'] is not None:
            rules.append('    %s <->> Internet\n' % role_name(name))
    with open(REACH, 'w') as fh:
        fh.write(HEADER % 'policy' + 'describe policies (default: deny)\n' + ''.join(rules) + 'end\n')
    print('roles %d, services %d, rules %d' % (len(m['endpoints']), len(m['services']), len(rules)))


if __name__ == '__main__':
    main()
