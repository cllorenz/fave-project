def _digest(path: str) -> str:
    with open(path, 'rb') as handle:
        return hashlib.sha256(handle.read()).hexdigest()


def trace_census(name: str, inserts: List[Insert]) -> Dict:
    """ Every number `TRACES.md` states about ONE trace, from that trace. """
    routers = {i.router for i in inserts}
    next_hops = {i.next_hop for i in inserts}
    per_router = collections.Counter(i.router for i in inserts)

    topology = derive_topology(inserts)
    homed = homes(inserts)
    per_home = collections.Counter(homed.values())

    return {
        'switches': len(topology.switches),
        'links': len(topology.links),
        'ports': sum(len(p) for p in topology.ports.values()),
        'degrees': {s: topology.degree(s) for s in topology.switches},
        'homing_switches': len(per_home),
        'prefixes_per_home': sorted(set(per_home.values())),
        'homes_nothing': sorted(set(topology.switches) - set(per_home)),
        'name': name,
        'sha256': _digest(os.path.join(RAW, name)),
        'inserts': len(inserts),
        'prefixes': len({i.prefix for i in inserts}),
        'routers': len(routers),
        'next_hops': len(next_hops),
        'names': len(routers | next_hops),
        'sinks': sorted(next_hops - routers),
        'sources': sorted(routers - next_hops),
        'edges': len(edges(inserts)),
        'collisions': collisions(inserts),
        'rules_per_router_min': min(per_router.values()),
        'rules_per_router_max': max(per_router.values()),
        'rules_per_router_mean': sum(per_router.values()) / len(per_router),
        'plen_histogram': dict(collections.Counter(i.plen for i in inserts)),
    }


def pair_census(left: List[Insert], right: List[Insert]) -> Dict:
    """ How the two traces differ -- the same network, routed two ways.

    They are not two samples of one thing: they share their prefix set exactly
    and differ only in where each router sends each prefix. That makes the pair
    a ready-made differential (CLOUD_BENCH_PLAN.md §2.3), so the overlap is
    measured rather than described.
    """
    lmap = {(i.router, i.prefix): i.next_hop for i in left}
    rmap = {(i.router, i.prefix): i.next_hop for i in right}
    shared = set(lmap) & set(rmap)

    def _same(field: str) -> bool:
        return ({getattr(i, field) for i in left}
                == {getattr(i, field) for i in right})

    return {
        'shared_keys': len(shared),
        'only_left': len(set(lmap) - set(rmap)),
        'only_right': len(set(rmap) - set(lmap)),
        'differing_next_hop': sum(1 for k in shared if lmap[k] != rmap[k]),
        # Measured as SET equality, not inferred from two equal counts: the
        # census reports 57 routers for both traces, and two 57-element sets
        # are not thereby the same 57 names.
        'same_prefixes': _same('prefix'),
        'same_routers': _same('router'),
        'same_next_hops': _same('next_hop'),
        'same_edges': (edges(left) == edges(right)),
    }


def census() -> Dict:
    """ Read the vendored traces -- after checking them -- and measure both. """
    verify_raw(RAW)
    traces = [(name, read_trace(os.path.join(RAW, name))) for name in TRACES]
    return {
        'traces': [trace_census(name, inserts) for name, inserts in traces],
        'pair': pair_census(traces[0][1], traces[1][1]),
    }


def _n(value: int) -> str:
    """ A count, in the plan's own thousands-separated spelling. """
    return '{:,}'.format(value)


def _table(header: Sequence[str], rows: Sequence[Sequence[str]],
           align: str = '') -> List[str]:
    align = align or 'l' * len(header)
    sep = {'l': '---', 'r': '---:', 'c': ':---:'}
    out = ['| ' + ' | '.join(header) + ' |',
           '|' + '|'.join(sep[a] for a in align) + '|']
    out.extend('| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows)
    return out


def render(c: Dict) -> str:
    """ `TRACES.md`, from the census. """
    out: List[str] = []
    w = out.append
    first, second = c['traces']
    pair = c['pair']

