""" What the Delta-net traces contain: the census, DERIVED (`TRACES.md`).

Same reasoning as `bench/wl_cloud/cloud_census.py`, and the same mechanism:
`TRACES.md` is GENERATED by this module and pinned byte for byte by
`test/test_deltanet_census.py`. Editing it by hand is a test failure.

The reason it exists here is sharper than "consistency", because these figures
had ALREADY rotted. `deltanet-traces/README.md` and CLOUD_BENCH_PLAN.md §2 both
carried three measurements taken by hand at vendoring time, and all three were
wrong:

  1. "the fourth field takes 18 distinct values in **180-220**" -- the count is
     right and the range is not. It is 170-260.

  2. "prefix lengths **14-25**, so genuine LPM" -- the conclusion survives and
     the figure does not. Lengths run 14-32. The tell is that 14-25 is 12
     lengths and the same sentence says 18 values; the missing length is /31,
     which no prefix in either trace uses.

  3. "**1,400 distinct prefixes**" for airtel2 -- right, and true of airtel1
     too, which nothing said.

None of the three was ever load-bearing, which is exactly why they survived: no
converter had been written yet, so nothing read them and nothing could
contradict them. How far off the stated range was is itself derived rather than
asserted here -- `render` counts it.

`plen_histogram` is the one table here that is EVIDENCE rather than description:
it is the D1 finding, rendered from the data, and the parser asserts the same
identity on every row it reads (`deltanet_trace.lpm_priority`).
"""

